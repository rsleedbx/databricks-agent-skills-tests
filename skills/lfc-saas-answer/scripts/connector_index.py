#!/usr/bin/env python3
"""connector_index.py [--check]: the Lakeflow Connect connectors on docs.databricks.com, each with its doc pages and,
for SaaS connectors, the ready-to-run pipeline notebook the docs publish. Writes ../references/connectors.md.

Everything comes from the public docs: the sitemap lists every `ingestion/lakeflow-connect/<connector>-pipeline` page,
and each pipeline page links its notebook (notebooks/source/saas-cdc/<connector>-pipeline.html, with an "open in
Databricks" import button on the page). The connector's other pages (concepts, connection, limits, faq, reference,
troubleshoot, source setup) are the sitemap entries that share its prefix. --check prints what would change instead of
writing, and exits 1 if anything would.
"""
from __future__ import annotations

import datetime as dt
import difflib
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "references", "connectors.md")
BASE = "https://docs.databricks.com/aws/en"


def fetch(url: str, timeout: int) -> str:
    with urllib.request.urlopen(url, timeout=timeout) as r:   # public docs: no credentials
        return r.read().decode("utf-8", "replace")


def status_of(html: str) -> str:
    """The badge between the title and the first section ("This feature is in Beta"); '' means generally available. A
    badge further down is for one feature of the connector (Salesforce formula fields), not the page."""
    flat = html.replace("\n", " ")
    if "</h1>" in flat:
        flat = flat[flat.rfind("</h1>") + len("</h1>"):]
    flat = re.sub(r"<[^>]+>", " ", flat.split("<h2")[0])
    m = re.search(r"This feature is in +([A-Z][A-Za-z]*(?: [A-Z][A-Za-z]*)?)", flat)
    return m.group(1) if m else ""


def name_of(html: str, prefix: str) -> str:
    m = re.search(r"<title[^>]*>([^<]+)", html)
    name = m.group(1) if m else ""
    name = re.sub(r"\s*\| Databricks.*", "", name)
    name = re.sub(r"^(Ingest data from|Create an?|Ingest) ", "", name, flags=re.IGNORECASE)
    name = re.sub(r" (ingestion )?pipeline.*$", "", name, flags=re.IGNORECASE)
    return name or prefix


def notebook_of(html: str) -> str:
    m = re.search(r"notebooks(?:%2F|/)source(?:%2F|/)saas-cdc(?:%2F|/)[a-z0-9-]+\.html", html)
    return m.group(0).replace("%2F", "/") if m else ""


def other_pages(prefix: str, pages: list[str]) -> str:
    cells = []
    for o in pages:
        if re.search(rf"/lakeflow-connect/{re.escape(prefix)}-[a-z0-9-]+$", o) and not o.endswith("-pipeline"):
            suffix = o[o.rfind("/" + prefix + "-") + len(prefix) + 2:]
            cells.append(f"[{suffix}]({o}) ")
    return "".join(cells)


def build() -> str:
    sitemap = fetch(f"{BASE}/sitemap.xml", 60)
    locs = [re.sub(r"<[^>]*>", "", x) for x in re.findall(r"<loc>[^<]+</loc>", sitemap)]
    pages = sorted({u for u in locs if re.search(r"/ingestion/lakeflow-connect/[a-z0-9-]+$", u)})
    pipelines = [u for u in pages if u.endswith("-pipeline")]
    if not pipelines:
        raise SystemExit("no lakeflow-connect pipeline pages in the sitemap")
    lines = [
        "# Lakeflow Connect connectors in the Databricks docs",
        "",
        ("Generated by [scripts/connector_index.py](../scripts/connector_index.py) from the public docs sitemap on "
        f"{dt.datetime.now(dt.timezone.utc):%Y-%m-%d}: every connector with an `ingestion/lakeflow-connect/<connector>-pipeline` "
        "page. **Status** is the badge under the page title (none means generally available). **Notebook** is the "
        "ready-to-run pipeline notebook the docs publish for the connector (fill in your connection and tables, or import "
        "it with the page's *Open in Databricks* button): start a test against a free developer org from it. Database "
        "connectors have no notebook."),
        "",
        "| Connector | Status | Pipeline page | Notebook | Other pages |",
        "|---|---|---|---|---|",
    ]
    for url in pipelines:
        slug = url.rsplit("/", 1)[-1]
        prefix = slug[: -len("-pipeline")]
        try:
            html = fetch(url, 30)
        except OSError:
            lines.append(f"| {prefix} | [page]({url}) | fetch failed | |")
            continue
        nb = notebook_of(html)
        others = other_pages(prefix, pages).rstrip(" ")
        lines.append(f"| {name_of(html, prefix)} | {status_of(html) or 'GA'} | [{slug}]({url}) | "
                     f"{'[notebook](' + BASE + '/' + nb + ')' if nb else ''} | {others} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = argv == ["--check"]
    if argv and not check:
        print("usage: connector_index.py [--check]", file=sys.stderr)
        return 2
    text = build()
    if check:
        with open(OUT) as fh:
            old = fh.read() if os.path.isfile(OUT) else ""
        if old.splitlines()[4:] == text.splitlines()[4:]:
            print("up to date")
            return 0
        for line in difflib.unified_diff(old.splitlines()[4:], text.splitlines()[4:], lineterm=""):
            print(line)
        return 1
    with open(OUT, "w") as fh:
        fh.write(text)
    rows = [x for x in text.splitlines() if x.startswith("| ")]
    print(f"wrote {os.path.normpath(OUT)}: {len(rows) - 1} connectors, "
          f"{sum(1 for x in rows if 'notebook](' in x)} with a notebook")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
