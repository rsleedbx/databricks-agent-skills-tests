#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///
"""coverage_page.py: the Lakeflow Connect by-database table, generated from results/runs/*.jsonl.

  uv run coverage_page.py                                   # print the table
  uv run coverage_page.py --write docs/lakeflow-connect-database.md   # replace it between the markers
  uv run coverage_page.py --check docs/lakeflow-connect-database.md   # exit 1 when the page is stale

A cell lists each cloud with its outcome: ✅ when a pass is recorded there and no failure is newer than it
(blocked and expected-stop runs never override a pass: they are the environment or a correct stop, not the
product). Otherwise the newest outcome there: ❌ fail, ⚠️ partial, ⛔ blocked. A cell whose every record is an
expected stop reads "not offered"; one with no record reads "–". A standard CDC pass whose gateway ran on
serverless adds "(serverless gateway)"; a query-based cell adds "with a DML round trip" when a dml run passed
on that cloud. The UC connection column counts connection runs and query-based passes (each used one). A ✅
links the prompt that reproduces it when prompts/lfc-matrix/<test>-<engine>.txt exists, unless every pass there
was run by hand (notes start "run by hand"): then it says so. NOT_OFFERED holds the few combinations the product's
docs rule out and no run has recorded. Only the repo's own
records are read (results/runs), not a plugin user's.
"""
import json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
START, END = "<!-- coverage:start (generated by coverage_page.py; edit results/runs, not this table) -->", "<!-- coverage:end -->"
ENGINES = [("lakebase", "Lakebase", "lakebase"), ("mysql", "MySQL 8.4", "mysql"), ("oracle", "Oracle 23ai Free", "oracle"),
           ("postgres", "PostgreSQL 16", "pg"), ("sqlserver", "SQL Server 2022", "sqlserver")]   # engine, row label, prompt name
COLS = [("connection", "UC connection, queried with [`remote_query`](https://docs.databricks.com/aws/en/query-federation/remote-queries)"),
        ("qbc", "Query-based"), ("fcqbc", "Query-based via foreign catalog"), ("icdc", "Integrated CDC"),
        ("scdc", "Standard CDC (gateway)")]
CLOUDS = [("aws", "AWS"), ("azure", "Azure"), ("gcp", "GCP")]
ICON = {"fail": "❌", "partial": "⚠️", "blocked": "⛔"}
# combinations the product doesn't offer, from its docs, for cells with no run at all (a run's expected stop says it too)
NOT_OFFERED = {("oracle", "scdc"): "https://docs.databricks.com/aws/en/ingestion/lakeflow-connect/oracle-integrated-overview"}


def records():
    out = []
    for f in sorted((REPO / "results" / "runs").glob("*.jsonl")):
        for i, line in enumerate(f.read_text().splitlines()):
            if line.strip():
                out.append(dict(json.loads(line), _order=(f.name, i)))
    return out


def status(recs):
    """recs: one engine x test x cloud, any order -> 'pass', 'not-offered', an outcome, or None."""
    if not recs:
        return None
    recs = sorted(recs, key=lambda r: (r["date"], r["_order"]))
    passes = [r for r in recs if r["outcome"] == "pass"]
    fails = [r for r in recs if r["outcome"] in ("fail", "partial")]
    if passes and not (fails and (fails[-1]["date"], fails[-1]["_order"]) > (passes[-1]["date"], passes[-1]["_order"])):
        return "pass"
    if all(r["outcome"] == "expected-stop" for r in recs):
        return "not-offered"
    # a product result (fail, partial) outranks the environment (blocked), whatever their order
    return next((r["outcome"] for r in reversed(recs) if r["outcome"] not in ("expected-stop", "blocked")), "blocked")


def cell(recs, engine, test, prompt):
    by = lambda t, c: [r for r in recs if r["subject"].get("engine") == engine and r["test"] == t
                       and (r.get("workspace") or {}).get("cloud") == c]
    parts, stops, passed = [], 0, []
    for c, label in CLOUDS:
        rs = by(test, c)
        if test == "connection":   # a query-based pass used a UC connection
            rs = rs + [r for r in by("qbc", c) + by("fcqbc", c) if r["outcome"] == "pass"]
        s = status(rs)
        if s is None:
            continue
        if s == "not-offered":
            stops += 1
        elif s == "pass":
            passed.append(label)
        else:
            parts.append(f"{ICON.get(s, s)} {label}")
    if not passed and not parts:
        if stops: return "not offered"
        return f"not offered ([docs]({NOT_OFFERED[(engine, test)]}))" if (engine, test) in NOT_OFFERED else "–"
    text = ""
    if passed:
        text = "✅ " + ", ".join(passed)
        p = [r for c, l in CLOUDS if l in passed for r in by(test, c) if r["outcome"] == "pass"]
        if test == "scdc" and any(((r.get("compute") or {}).get("gateway") or {}).get("ran_on") == "serverless" for r in p):
            text += " (serverless gateway)"
        if test == "qbc" and any(r["outcome"] == "pass" for c, l in CLOUDS if l in passed for r in by("dml", c)):
            text += ", with a DML round trip"
        by_hand = p and all(str(r.get("notes", "")).startswith("run by hand") for r in p)
        if by_hand:
            text += ", by hand"
        f = REPO / "prompts" / "lfc-matrix" / f"{test}-{prompt}.txt"
        if test != "connection" and not by_hand and f.exists():
            text = f"[{text}](../prompts/lfc-matrix/{f.name})"
    return "; ".join(([text] if text else []) + parts)


def table():
    recs = records()
    rows = ["| Database | " + " | ".join(h for _, h in COLS) + " |", "|---|" + "---|" * len(COLS)]
    for engine, label, prompt in ENGINES:
        rows.append(f"| {label} | " + " | ".join(cell(recs, engine, t, prompt) for t, _ in COLS) + " |")
    rows.append("")
    rows.append("✅ passed (no newer failure) · ⚠️ partial · ❌ failed · ⛔ blocked by the workspace or environment · "
                "not offered: every run stopped correctly because the product doesn't offer it · –: no run recorded")
    return "\n".join(rows)


def render(page):
    s = page.read_text()
    if START not in s or END not in s:
        sys.exit(f"{page}: no {START!r} ... {END!r} markers")
    a, b = s.index(START) + len(START), s.index(END)
    return s[:a] + "\n" + table() + "\n" + s[b:]


def main():
    if len(sys.argv) == 3 and sys.argv[1] in ("--write", "--check"):
        page = Path(sys.argv[2])
        new = render(page)
        if sys.argv[1] == "--write":
            page.write_text(new); print(f"wrote {page}")
        elif new != page.read_text():
            sys.exit(f"{page} is stale: uv run skills/lfc-test-results/scripts/coverage_page.py --write {page}")
        else:
            print(f"{page} matches results/runs")
        return
    print(table())


if __name__ == "__main__":
    main()
